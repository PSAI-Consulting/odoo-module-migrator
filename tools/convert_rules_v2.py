"""Convert the rules of migration_scripts to the v2 format.

Default: the hand-written files (curated layer), one v2 block per rule.
``--generated``: the extracted files (generated.yaml, modules.yaml, files
whose header says "Generated by"), one v2 flow mapping per line, always
``confidence: generated`` (only a review promotes an extracted rule); the
extractors call it themselves after writing (``convert_generated_files``).
candidates.yaml is never touched. Each legacy entry is replaced in place:
comments, order and the historical message are kept, so the legacy
projection stays identical (``tools/rules_baseline.py --check``).

A source of the historical message (or of the comment right above it) becomes
a structured evidence, and the rule ``confidence: verified``, only when it is
proven in the local repositories (``--repos``, bare clones):

* ``odoo <sha>`` / ``enterprise <sha>``: the commit exists, and a quoted
  title, if any, is the subject of the commit (the evidence title is the
  real subject read from git);
* ``https://github.com/OCA/<repo>/commit/<sha>``: the commit exists in
  ``oca/<repo>.git``;
* ``OpenUpgrade <version> <path>``: the file exists on that branch.

Anything else stays a legacy message (LegacyEvidence): never promoted.

Usage::

    python tools/convert_rules_v2.py --repos D:/Odoo/.repos [--dry-run] [FILE ...]
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import subprocess
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from odoo_module_migrate.migration_rules import legacy, loader
from odoo_module_migrate.migration_rules.models import (
    OriginLayer,
    RuleKind,
)

COMMIT_RE = re.compile(r"\b(odoo|enterprise)\s+(?:commit\s+)?([0-9a-f]{7,40})\b")
TITLE_AFTER_RE = re.compile(r"""^\s*:?\s*(?:'(?P<s>[^\n]*?)'|"(?P<d>[^\n]*?)"|«\s*(?P<g>[^»]*?)\s*»)""")
OCA_RE = re.compile(r"github\.com/OCA/([\w.-]+)/commit/([0-9a-f]{7,40})")
OU_RE = re.compile(r"OpenUpgrade\s+(\d+\.0)\s+(openupgrade_scripts/\S+?|odoo/addons/\S+?|addons/\S+?)(?=[\s'\",;)]|$)")
BLANK = object()


def q(value) -> str:
    """YAML scalar: JSON strings are YAML double-quoted scalars."""
    if value is None:
        return "null"
    return json.dumps(value, ensure_ascii=False)


class Repos:
    def __init__(self, base: pathlib.Path | None):
        self.base = base
        self.cache: dict[tuple, str | None] = {}

    def _git(self, git_dir: pathlib.Path | None, *args) -> str | None:
        if git_dir is None or not git_dir.is_dir():
            return None
        result = subprocess.run(["git", f"--git-dir={git_dir}", *args], capture_output=True, text=True, check=False,
                                encoding="utf-8", errors="replace")
        return result.stdout.strip() if result.returncode == 0 else None

    def subject(self, repository: str, sha: str) -> tuple[str, str] | None:
        """(full sha, subject) of a commit of odoo / enterprise / oca/<repo>."""
        key = ("commit", repository, sha)
        if key not in self.cache:
            git_dir = self.base / f"{repository}.git" if self.base else None
            out = self._git(git_dir, "log", "-1", "--no-walk", "--format=%H%x09%s", f"{sha}^{{commit}}")
            self.cache[key] = tuple(out.split("\t", 1)) if out and "\t" in out else None
        return self.cache[key]

    def openupgrade_file(self, version: str, path: str) -> bool:
        key = ("ou", version, path)
        if key not in self.cache:
            git_dir = self.base / "oca" / "OpenUpgrade.git" if self.base else None
            ok = any(self._git(git_dir, "cat-file", "-e", f"{ref}:{path}") is not None
                     for ref in (version, f"origin/{version}", f"refs/heads/{version}"))
            self.cache[key] = ok
        return bool(self.cache[key])


def references(text: str, repos: Repos) -> tuple[list[dict], bool]:
    """(structured evidences, every reference proven) of a free text."""
    evidences, proven = [], True
    for match in COMMIT_RE.finditer(text):
        repository, sha = match.groups()
        found = repos.subject(repository, sha)
        if not found:
            proven = False
            continue
        full, subject = found
        quoted = TITLE_AFTER_RE.match(text[match.end():])
        if quoted:
            title = next(g for g in quoted.groups() if g is not None).strip()
            if title and not (subject.startswith(title.rstrip(".…")) or title in subject):
                proven = False  # the quoted title is not this commit's
                continue
        evidences.append({"repository": repository, "commit": full[:12], "title": subject})
    for match in OCA_RE.finditer(text):
        repo, sha = match.groups()
        found = repos.subject(f"oca/{repo}", sha)
        if not found:
            proven = False
            continue
        evidences.append({"repository": "oca", "commit": found[0][:12], "title": found[1],
                          "url": f"https://github.com/OCA/{repo}/commit/{found[0]}"})
    for match in OU_RE.finditer(text):
        version, path = match.groups()
        if repos.openupgrade_file(version, path):
            evidences.append({"repository": "openupgrade", "file": path, "note": f"OpenUpgrade {version}"})
        else:
            proven = False
    unique = []
    for item in evidences:
        if item not in unique:
            unique.append(item)
    return unique, proven and bool(unique)


FIELDS = {
    RuleKind.DEPRECATED_MODULE: lambda p: [("module", p.module), ("change", str(p.change)), ("target", p.target or BLANK),
                                           ("message", p.message if p.message is not None else BLANK)],
    RuleKind.REMOVED_MODEL: lambda p: [("model", p.model), ("message", p.message)],
    RuleKind.RENAMED_MODEL: lambda p: [("old_model", p.old_model), ("new_model", p.new_model), ("message", p.message)],
    RuleKind.REMOVED_FIELD: lambda p: [("model", p.model), ("field", p.field),
                                       ("message", p.message if p.message is not None else BLANK)],
    RuleKind.RENAMED_FIELD: lambda p: [("model", p.model), ("old_field", p.old_field), ("new_field", p.new_field),
                                       ("message", p.message if p.message is not None else BLANK)],
    RuleKind.RENAMED_METHOD: lambda p: [("model", p.model), ("old_method", p.old_method), ("new_method", p.new_method),
                                        ("message", p.message if p.message is not None else BLANK)],
    RuleKind.FIELD_TYPE: lambda p: [("model", p.model), ("field", p.field), ("old_type", p.old_type),
                                    ("new_type", p.new_type), ("message", p.message)],
    RuleKind.FIELD_PROPERTY: lambda p: [("model", p.model), ("field", p.field), ("property", p.property),
                                        ("old_value", p.old_value), ("new_value", p.new_value), ("message", p.message)],
    RuleKind.MENU_PARENT_HINT: lambda p: [("removed_parent", p.removed_parent), ("surviving_child", p.surviving_child),
                                          ("candidate_parent", p.candidate_parent), ("message", p.message)],
    RuleKind.TEXT_REPLACE: lambda p: [("replacement", p.value)],
    RuleKind.TEXT_ERROR: lambda p: [("message", p.value)],
    RuleKind.TEXT_WARNING: lambda p: [("message", p.value)],
}


def v2_block(rule, indent: str, repos: Repos, key_text: str = "") -> list[str]:
    fields = [(k, v) for k, v in FIELDS[rule.kind](rule.payload) if v is not BLANK]
    sources = " ".join(e.text for e in rule.evidence if e.location in ("value", "comment", "inline_comment"))
    evidences, proven = references(sources, repos)
    body = [("schema_version", "2"), ("kind", str(rule.kind))]
    body += [(k, q(v)) for k, v in fields if k != "message"]
    if proven:
        body.append(("confidence", "verified"))
    elif rule.kind == RuleKind.TEXT_WARNING:
        body.append(("confidence", "heuristic"))
    if key_text:  # text rule: the pattern stays the key, the value becomes a mapping
        lines, first = [f"{indent}{key_text}:"], indent + "  "
        pad = first
    else:
        lines, first = [], f"{indent}- "
        pad = indent + "  "
    for n, (key, value) in enumerate(body):
        lines.append(f"{first if n == 0 else pad}{key}: {value}")
    if proven:
        lines.append(f"{pad}evidence:")
        for item in evidences:
            for n, (key, value) in enumerate(item.items()):
                lines.append(f"{pad}  {'- ' if n == 0 else '  '}{key}: {q(value)}")
    for key, value in fields:
        if key == "message":
            lines.append(f"{pad}message: {q(value)}")
    return lines


def v2_flow(rule, repos: Repos, key_text: str = "") -> str:
    """One-line v2 entry of an extracted rule (``- {...}`` or ``'pattern': {...}``)."""
    fields = [(k, v) for k, v in FIELDS[rule.kind](rule.payload) if v is not BLANK]
    # the comment right above (text rules) or after (modules) holds the source
    sources = " ".join(e.text for e in rule.evidence if e.location in ("value", "comment", "inline_comment"))
    evidences, _proven = references(sources, repos)
    parts = ["schema_version: 2", f"kind: {rule.kind}"]
    parts += [f"{k}: {q(v)}" for k, v in fields if k != "message"]
    parts.append("confidence: generated")
    if evidences:  # each reference checked in the repositories
        parts.append("evidence: [" + ", ".join(
            "{" + ", ".join(f"{k}: {q(v)}" for k, v in item.items()) + "}" for item in evidences
        ) + "]")
    parts += [f"message: {q(v)}" for k, v in fields if k == "message"]
    body = "{" + ", ".join(parts) + "}"
    return f"{key_text}: {body}" if key_text else f"- {body}"


def convert_file(path: pathlib.Path, category: str, repos: Repos, dry_run: bool, generated: bool = False) -> int:
    rule_file = loader.load_file(path, category, path.parent.parent.parent)
    wanted = OriginLayer.GENERATED if generated else OriginLayer.CURATED
    if rule_file.layer != wanted or not rule_file.rules:
        return 0
    raw = path.read_bytes().decode("utf-8")
    newline = "\r\n" if "\r\n" in raw else "\n"
    lines = raw.replace("\r\n", "\n").split("\n")
    by_line = {r.origin.line: r for r in rule_file.rules if not r.structured}
    # spans of the entries (first line, last line) from the YAML nodes
    node = yaml.compose(raw)
    spans = {}
    if legacy.CATEGORIES[category].container == "list":
        for item in node.value:
            spans[item.start_mark.line + 1] = (item.start_mark, item.end_mark, None)
    else:
        for _ext, mapping in node.value:
            for key, value in mapping.value:
                spans[key.start_mark.line + 1] = (key.start_mark, value.end_mark, key.end_mark)
    converted = 0
    for line_no in sorted(by_line, reverse=True):
        rule = by_line[line_no]
        start, end, key_end = spans[line_no]
        last = end.line if end.column == 0 and end.line > start.line else end.line + 1
        tail = lines[last - 1][end.column:] if end.line + 1 == last else ""
        inline = tail.strip()
        indent = lines[line_no - 1][:start.column]
        if legacy.CATEGORIES[category].container == "list":
            indent = indent.removesuffix("- ")
        block = []
        if inline and not inline.startswith("#"):
            raise SystemExit(f"{path}:{line_no}: unexpected text after the entry: {inline!r}")
        key_text = lines[line_no - 1][start.column:key_end.column] if key_end is not None else ""
        if generated:
            block.append(indent + v2_flow(rule, repos, key_text) + (f"  {inline}" if inline else ""))
        else:
            if inline:
                block.append(f"{indent}{inline}")
            block += v2_block(rule, indent, repos, key_text)
        lines[line_no - 1:last] = block
        converted += 1
    if converted and generated:
        # the header of an extracted file describes its format
        lines = ["# Format: schema_version 2, one rule per line (docs/migration_rules.md)"
                 if re.match(r"# Format: \[", line) else line for line in lines]
    if converted and not dry_run:
        path.write_bytes(newline.join(lines).encode("utf-8"))
    return converted


def convert_generated_files(paths, repos_base: pathlib.Path | None) -> int:
    """Called by the extractors on the files they just wrote."""
    repos = Repos(repos_base)
    total = 0
    for path in map(pathlib.Path, paths):
        path = path.resolve()
        category = path.parent.parent.name
        if category in legacy.CATEGORIES and path.stem != "candidates":
            total += convert_file(path, category, repos, False, generated=True)
    return total


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--repos", type=pathlib.Path, help="folder of the bare clones (odoo.git, enterprise.git, oca/)")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--generated", action="store_true",
                        help="convert the extracted files (one line per rule, confidence: generated)")
    parser.add_argument("files", nargs="*", type=pathlib.Path)
    args = parser.parse_args(argv)
    repos = Repos(args.repos)
    if args.repos is None:
        print("no --repos: no source can be proven, rules are converted without evidence", file=sys.stderr)
    files = args.files or sorted(p for c in legacy.CATEGORIES for p in (loader.SCRIPTS_DIR / c).glob("*/*.yaml"))
    total = 0
    for path in files:
        path = path.resolve()
        category = path.relative_to(loader.SCRIPTS_DIR).parts[0]
        count = convert_file(path, category, repos, args.dry_run, generated=args.generated)
        if count:
            print(f"{path.relative_to(loader.SCRIPTS_DIR).as_posix()}: {count} rule(s)")
        total += count
    print(f"{total} rule(s) converted{' (dry run)' if args.dry_run else ''}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
