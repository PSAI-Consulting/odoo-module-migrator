"""Common loader of the rule files of ``migration_scripts``.

Every consumer (migration scripts, RAG, extractors, validator, upgrade_code
aliases) reads the rules through this module:

* files are found exactly as ``BaseMigrationScript.parse_rules`` always did
  (``glob('<category>/<step>/*.yaml')`` sorted: curated.yaml before
  generated.yaml, "first rule wins");
* each entry becomes a typed :class:`~.models.Rule` with its file, line and
  layer (``yaml.compose`` marks), legacy or v2;
* :func:`legacy_documents` gives back, file by file, the exact historical data
  (a v2 entry is projected to its historical list / value).

Parsed files are memoised on (path, size, mtime): a nested change invalidates
them. Callers always receive copies.
"""

from __future__ import annotations

import copy
import glob
import hashlib
import importlib
import inspect
import os
import pathlib
import re
from dataclasses import dataclass, field
from typing import Any

import yaml

from . import legacy
from .models import (
    PRIORITY_CANDIDATE,
    PRIORITY_CURATED_LEGACY,
    PRIORITY_CURATED_STRUCTURED,
    PRIORITY_GENERATED,
    PRIORITY_HEURISTIC,
    Automation,
    Confidence,
    LegacyEvidence,
    Origin,
    OriginLayer,
    PythonTransform,
    Rule,
    RuleError,
    RuleKind,
    Step,
    content_fingerprint,
)

SCRIPTS_DIR = pathlib.Path(__file__).resolve().parent.parent / "migration_scripts"
PYTHON_PACKAGE = "odoo_module_migrate.migration_scripts.python_scripts"
_GENERATED_HEADER = re.compile(r"^#.*\bgenerated by\b", re.IGNORECASE)


# ------------------------------------------------------------------ files


def file_layer(path: pathlib.Path, lines: list[str]) -> OriginLayer:
    """candidates.yaml: inactive candidates; generated.yaml, modules.yaml and
    the files whose header says "Generated by": extracted; else hand-written."""
    if path.stem == "candidates":
        return OriginLayer.CANDIDATE
    if path.stem in ("generated", "modules"):
        return OriginLayer.GENERATED
    for line in lines[:12]:
        if not line.startswith("#"):
            break
        if _GENERATED_HEADER.match(line):
            return OriginLayer.GENERATED
    return OriginLayer.CURATED


def rule_files(category: str, step: str, root: pathlib.Path | None = None) -> list[pathlib.Path]:
    """Same files, same order as the historical loader."""
    pattern = os.path.join(str(root or SCRIPTS_DIR), category, step, "*.yaml")
    return [pathlib.Path(p) for p in sorted(glob.glob(pattern))]


def step_names(category: str, root: pathlib.Path | None = None) -> list[str]:
    base = (root or SCRIPTS_DIR) / category
    return sorted(p.name for p in base.iterdir() if p.is_dir() and p.name.startswith("migrate_")) if base.is_dir() else []


def script_steps(root: pathlib.Path | None = None) -> list[str]:
    """Steps that a migration script loads (migrate_*.py)."""
    return sorted(p.stem for p in (root or SCRIPTS_DIR).glob("migrate_*.py"))


@dataclass
class RuleFile:
    path: pathlib.Path
    rel_path: str
    category: str
    step: Step
    layer: OriginLayer
    rules: tuple[Rule, ...]
    raw_document: Any  # historical data of the file (v2 entries projected): shared, never mutate
    lines: list[str] = field(repr=False, default_factory=list)

    @property
    def document(self) -> Any:
        """A copy of the historical data (the parsed file is memoised)."""
        return copy.deepcopy(self.raw_document)


_CACHE: dict[tuple[str, int, int], RuleFile] = {}


def _group_comments(lines: list[str], index: int, keep_header: bool) -> list[str]:
    """Comments of the group of an entry without its own comment: the entries
    (or the extension section) right above it share the same comment."""
    i = index - 1
    while i >= 0 and lines[i].strip() and not lines[i].strip().startswith("#"):
        i -= 1
    return _comments_above(lines, i + 1, keep_header) if i < index - 1 else []


def _comments_above(lines: list[str], index: int, keep_header: bool = True) -> list[str]:
    """Last paragraph of the contiguous comment lines right above line
    ``index`` (0-based). The header of a generated file (a block starting on
    its first line) describes the generator, not the rule."""
    found = []
    i = index - 1
    while i >= 0 and lines[i].strip().startswith("#"):
        found.append(lines[i].strip())
        i -= 1
    found.reverse()
    separators = [n for n, line in enumerate(found) if line == "#"]
    if separators:
        return found[separators[-1] + 1:]
    return [] if i < 0 and not keep_header else found


def _inline_comment(lines: list[str], node: yaml.Node) -> str:
    start, end = node.start_mark, node.end_mark
    if end.line != start.line or end.line >= len(lines):
        return ""
    rest = lines[end.line][end.column:].strip()
    return rest[1:].strip() if rest.startswith("#") else ""


def _stable_id(kind: RuleKind, step: Step, key: tuple, layer: OriginLayer) -> str:
    parts = []
    for value in key:
        text = str(value)
        if kind in (RuleKind.TEXT_REPLACE, RuleKind.TEXT_ERROR, RuleKind.TEXT_WARNING) and value is key[-1]:
            text = hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]
        parts.append(text)
    return f"{kind}/{step.name}/{'|'.join(parts)}@{layer}"


def _priority(layer: OriginLayer, structured: bool, confidence: Confidence) -> int:
    if layer == OriginLayer.CANDIDATE:
        return PRIORITY_CANDIDATE
    if layer == OriginLayer.GENERATED:
        return PRIORITY_GENERATED
    if confidence == Confidence.HEURISTIC:
        return PRIORITY_HEURISTIC
    return PRIORITY_CURATED_STRUCTURED if structured else PRIORITY_CURATED_LEGACY


def _make_rule(category, step, layer, rel, node, entry, lines, seen_ids, extension="", pattern="") -> tuple[Rule, Any]:
    line = node.start_mark.line + 1
    where = f"{rel}:{line}"
    if legacy.is_v2(entry):
        if entry.get("schema_version") != legacy.SCHEMA_VERSION:
            raise RuleError(f"unsupported schema_version {entry.get('schema_version')!r}", where)
        kind = category.kind
        if "kind" in entry and entry["kind"] != str(kind):
            raise RuleError(f"kind {entry['kind']!r} does not match the folder {category.folder} ({kind})", where)
        for name, expected in (("from_version", step.from_version), ("to_version", step.to_version)):
            if name in entry and str(entry[name]) != str(expected):
                raise RuleError(f"{name} {entry[name]!r} does not match the folder {step.name} ({expected})", where)
        if layer not in (OriginLayer.CURATED, OriginLayer.GENERATED):
            raise RuleError(f"schema_version 2 entries do not belong to {layer} files", where)
        payload = legacy.v2_payload(kind, entry, where, extension, pattern)
        structured_evidence = legacy.v2_evidence(entry, where)
        # the historical message stays a legacy (never official) evidence
        evidence = structured_evidence + legacy.legacy_evidence(payload)
        pre, post = legacy.v2_conditions(entry, payload, where)
        default = "generated" if layer == OriginLayer.GENERATED else "unknown"
        confidence = Confidence.parse(entry.get("confidence", default), where)
        if layer == OriginLayer.GENERATED and confidence != Confidence.GENERATED:
            # only a review (a curated rule) may promote an extracted rule
            raise RuleError(f"a generated rule has confidence: generated, not {confidence}", where)
        if confidence == Confidence.VERIFIED and not structured_evidence:
            raise RuleError("a verified rule needs a structured evidence", where)
        automation = Automation.parse(entry["automation"], where) if "automation" in entry else \
            legacy.legacy_automation(kind, payload, layer)
        historical = legacy.project(kind, payload)
        structured, note = True, str(entry.get("note") or "")
    else:
        kind = category.kind
        payload = legacy.legacy_payload(category, entry, where, extension, pattern)
        evidence, pre, post = legacy.legacy_evidence(payload), (), ()
        confidence = legacy.legacy_confidence(kind, layer)
        automation = legacy.legacy_automation(kind, payload, layer)
        historical, structured, note = entry, False, ""
    keep_header = layer == OriginLayer.CURATED
    comments = [c.lstrip("#").strip() for c in _comments_above(lines, node.start_mark.line, keep_header)]
    extra = []
    if any(comments):
        extra.append(LegacyEvidence("\n".join(c for c in comments if c), "comment"))
    else:
        group = [c.lstrip("#").strip() for c in _group_comments(lines, node.start_mark.line, keep_header)]
        if any(group):
            extra.append(LegacyEvidence("\n".join(c for c in group if c), "group_comment"))
    inline = _inline_comment(lines, node)
    if inline:
        extra.append(LegacyEvidence(inline, "inline_comment"))
    base_id = _stable_id(kind, step, payload.key(), layer)
    count = seen_ids.get(base_id, 0) + 1
    seen_ids[base_id] = count
    rule = Rule(
        stable_id=base_id if count == 1 else f"{base_id}#{count}",
        kind=kind,
        step=step,
        origin=Origin(rel, line, layer, content_fingerprint([str(kind), historical, structured])),
        priority=_priority(layer, structured, confidence),
        payload=payload,
        confidence=confidence,
        automation=automation,
        evidence=tuple(evidence) + tuple(extra),
        preconditions=pre,
        postconditions=post,
        schema_version=2 if structured else 1,
        legacy=copy.deepcopy(historical),
        note=note,
    )
    return rule, historical


def _parse(path: pathlib.Path, category: str, root: pathlib.Path, seen_ids: dict) -> RuleFile:
    cat = legacy.CATEGORIES[category]
    rel = path.relative_to(root).as_posix()
    step = Step.parse(path.parent.name)
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    layer = file_layer(path, lines)
    loader = yaml.SafeLoader(text)
    try:
        try:
            node = loader.get_single_node()
        except yaml.YAMLError as exc:
            mark = getattr(exc, "problem_mark", None)
            raise RuleError(f"invalid YAML: {exc}", f"{rel}:{mark.line + 1 if mark else 1}") from None
        rules: list[Rule] = []
        if node is None:
            return RuleFile(path, rel, category, step, layer, (), None, lines)
        if layer == OriginLayer.CANDIDATE:
            raise RuleError("candidates.yaml must stay commented: an active candidate would be applied",
                            f"{rel}:{node.start_mark.line + 1}")
        if cat.container == "list":
            if not isinstance(node, yaml.SequenceNode):
                raise RuleError("a list of rules is expected", f"{rel}:{node.start_mark.line + 1}")
            document = []
            for item in node.value:
                entry = loader.construct_object(item, deep=True)
                rule, historical = _make_rule(cat, step, layer, rel, item, entry, lines, seen_ids)
                rules.append(rule)
                document.append(historical)
        else:
            if not isinstance(node, yaml.MappingNode):
                raise RuleError("{extension: {pattern: value}} is expected", f"{rel}:{node.start_mark.line + 1}")
            document = {}
            for ext_node, rules_node in node.value:
                extension = loader.construct_object(ext_node, deep=True)
                where = f"{rel}:{ext_node.start_mark.line + 1}"
                if not isinstance(extension, str) or not legacy.EXTENSION_RE.match(extension):
                    raise RuleError(f"invalid extension {extension!r}", where)
                if not isinstance(rules_node, yaml.MappingNode):
                    raise RuleError(f"{{pattern: value}} expected under {extension}", where)
                # a repeated key replaces the whole mapping, as yaml.safe_load does
                bucket = document[extension] = {}
                for key_node, value_node in rules_node.value:
                    pattern = loader.construct_object(key_node, deep=True)
                    value = loader.construct_object(value_node, deep=True)
                    try:
                        re.compile(pattern)
                    except (re.error, TypeError) as exc:
                        raise RuleError(f"invalid regex {pattern!r}: {exc}", f"{rel}:{key_node.start_mark.line + 1}") from None
                    rule, historical = _make_rule(
                        cat, step, layer, rel, key_node, value, lines, seen_ids, extension, pattern
                    )
                    rules.append(rule)
                    bucket[pattern] = historical
        return RuleFile(path, rel, category, step, layer, tuple(rules), document, lines)
    finally:
        loader.dispose()


def load_file(path: pathlib.Path, category: str, root: pathlib.Path | None = None) -> RuleFile:
    """Parsed rule file (memoised on path, size and mtime)."""
    root = root or SCRIPTS_DIR
    stat = path.stat()
    key = (str(path.resolve()), stat.st_size, stat.st_mtime_ns)
    cached = _CACHE.get(key)
    if cached is None:
        # ids made unique across the files of a step by ruleset.load_rules
        cached = _parse(path, category, root, {})
        if len(_CACHE) > 2000:
            _CACHE.clear()
        _CACHE[key] = cached
    return cached


def legacy_documents(category: str, step: str, root: pathlib.Path | None = None) -> list[tuple[pathlib.Path, Any]]:
    """[(file, historical data)] of a step, in loading order (copies)."""
    result = []
    for path in rule_files(category, step, root):
        document = load_file(path, category, root).raw_document
        if document:  # empty or comments only
            result.append((path, copy.deepcopy(document)))
    return result


def step_rules(category: str, step: str, root: pathlib.Path | None = None) -> list[Rule]:
    return [r for path in rule_files(category, step, root) for r in load_file(path, category, root).rules]


# ------------------------------------------------------------------ python transforms


def python_transform_functions(step: str) -> list[Any]:
    """Public functions of ``python_scripts/<step>/*.py`` (sorted files: the
    same order on every OS)."""
    pattern = os.path.join(str(SCRIPTS_DIR), "python_scripts", step, "*.py")
    functions = []
    for path in sorted(glob.glob(pattern)):
        module_name = ".".join([PYTHON_PACKAGE, step, os.path.basename(path).split(".")[0]])
        module = importlib.import_module(module_name)
        for name, value in inspect.getmembers(module, inspect.isfunction):
            if not name.startswith("_"):
                functions.append(value)
    return functions


def python_rule(function: Any, step: Step) -> Rule:
    """Inventory entry of a global function (never converted to YAML)."""
    try:
        source_file = inspect.getsourcefile(function) or ""
        line = inspect.getsourcelines(function)[1]
    except (OSError, TypeError):
        source_file, line = "", 0
    try:
        rel = pathlib.Path(source_file).resolve().relative_to(SCRIPTS_DIR).as_posix()
    except ValueError:
        rel = pathlib.Path(source_file).name
    module = inspect.getmodule(function)
    metadata = (getattr(module, "MIGRATION_RULES", {}) or {}).get(function.__name__, {})
    doc = inspect.getdoc(function) or ""
    where = f"{rel}:{line}"
    unknown = set(metadata) - {"automation", "confidence", "evidence", "preconditions", "postconditions",
                                "upgrade_code", "description"}
    if unknown:
        raise RuleError(f"unknown MIGRATION_RULES field(s) {', '.join(sorted(unknown))}", where)
    payload = PythonTransform(function.__module__, function.__name__,
                              str(metadata.get("description") or doc.split("\n\n")[0]),
                              bool(metadata.get("upgrade_code", False)))
    evidence = legacy.v2_evidence(metadata, where) if metadata.get("evidence") else ()
    if doc:
        evidence += (LegacyEvidence(doc, "docstring"),)
    pre, post = legacy.v2_conditions(metadata, payload, where) if metadata else ((), ())
    structured = bool(metadata)
    confidence = Confidence.parse(metadata.get("confidence", "unknown"), where)
    return Rule(
        stable_id=f"{RuleKind.PYTHON_TRANSFORM}/{step.name}/{function.__module__}.{function.__name__}@python",
        kind=RuleKind.PYTHON_TRANSFORM,
        step=step,
        origin=Origin(rel, line, OriginLayer.PYTHON, content_fingerprint([function.__module__, function.__name__])),
        priority=PRIORITY_CURATED_STRUCTURED if structured else PRIORITY_CURATED_LEGACY,
        payload=payload,
        confidence=confidence,
        automation=Automation.parse(metadata.get("automation", "deterministic"), where),
        evidence=evidence,
        preconditions=pre,
        postconditions=post,
        schema_version=2 if structured else 1,
        legacy=f"{function.__module__}.{function.__qualname__}",
    )


def python_text_rules(script_class: Any, step: Step) -> list[Rule]:
    """Text rules written in a migrate_*.py script (class dictionaries)."""
    import ast

    path = pathlib.Path(inspect.getfile(script_class))
    rel = path.resolve().relative_to(SCRIPTS_DIR).as_posix()
    lines: dict[str, int] = {}
    for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            lines.setdefault(node.value, node.lineno)
    rules = []
    for category in ("text_replaces", "text_errors", "text_warnings"):
        cat = legacy.CATEGORIES[category]
        for extension, patterns in (getattr(script_class, cat.attribute, {}) or {}).items():
            for pattern, value in patterns.items():
                payload = legacy.TextRule(extension, pattern, value)
                line = lines.get(pattern, 0)
                rules.append(Rule(
                    stable_id=_stable_id(cat.kind, step, payload.key(), OriginLayer.PYTHON),
                    kind=cat.kind,
                    step=step,
                    origin=Origin(rel, line, OriginLayer.PYTHON, content_fingerprint([str(cat.kind), value])),
                    priority=PRIORITY_CURATED_LEGACY,
                    payload=payload,
                    confidence=legacy.legacy_confidence(cat.kind, OriginLayer.PYTHON),
                    automation=legacy.legacy_automation(cat.kind, payload, OriginLayer.PYTHON),
                    evidence=legacy.legacy_evidence(payload),
                    legacy=value,
                ))
    return rules
